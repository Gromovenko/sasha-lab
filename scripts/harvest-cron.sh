#!/bin/bash
# Еженедельный сбор базы знаний. Ставится в cron на сервере проекта
# 77.105.168.153 (он живёт в UTC):
#   0 0 * * 0 /opt/sasha-lab/scripts/harvest-cron.sh   # вс 03:00 МСК
#
# Публикацию скрипт НЕ делает намеренно: сборка статики и рестарт — действие
# человека. Автомат, который сам выкатывает страницы по свежесобранным фактам,
# рано или поздно опубликует страницу по машине, о которой знает одну строчку,
# и сделает это ночью, когда никто не смотрит.
set -u
cd /opt/sasha-lab || exit 1

# ЗАМОК. Сбор всегда идёт в ОДНОМ экземпляре на сервер: и очередь полного
# захода, и еженедельный крон берут один и тот же flock. Без него воскресный
# крон садится поверх идущего сутками полного захода — двойная нагрузка на нас
# и, что хуже, двойная частота запросов к каждому чужому сайту, то есть ровно
# тот случай, ради которого всё остальное здесь и меряется.
LOCK=/tmp/sashalab-harvest.lock
if [ -z "${HARVEST_LOCKED:-}" ]; then
  export HARVEST_LOCKED=1
  flock -E 99 -n "$LOCK" "$0" "$@"; rc=$?
  [ "$rc" = 99 ] && echo "$(TZ=Europe/Moscow date '+%F %H:%M МСК') сбор уже идёт — недельный заход пропущен" >> /var/log/sashalab-harvest.log
  exit "$rc"
fi
LOG=/var/log/sashalab-harvest.log
exec >> "$LOG" 2>&1
echo "=== $(TZ=Europe/Moscow date '+%F %H:%M МСК') сбор базы знаний"

# Каждый источник отдельной командой: упавший не должен уносить остальные.
# Потолок страниц на источник за заход: еженедельно 60 (догоняем новое),
# первичное наполнение — HARVEST_LIMIT=400 разово руками. Drive2 в реестре
# выключен (robots.txt запрещает сбор) — команда это скажет и пойдёт дальше.
LIMIT="${HARVEST_LIMIT:-60}"

# Источник «только заголовки» (hidplanet.com) чужой сервер почти не трогает:
# за заход это ОДНА скачанная карта сайта вместо тысяч страниц, дальше всё
# считается у нас. Поэтому общий потолок в 60 ему не нужен — иначе форум на
# 64 тысячи тем догонялся бы годами. Идёт первым: после него заход по kind
# community не найдёт у него ничего нового.
timeout 1800 node harvest/run.js crawl www.hidplanet.com || echo '  ! hidplanet не доехал'

for what in works parts community; do
  timeout 14400 node harvest/run.js crawl "$what" --limit "$LIMIT" || echo "  ! этап $what не доехал"
done
# Разбор фактов — локальные правила без ИИ, ~12 док/с. Лимит 2000 за заход при
# 4 тыс. новых документов в сутки копил хвост годами; 30 тыс. ≈ 45 минут.
timeout 3600 node harvest/run.js facts --limit 30000 || echo '  ! разбор фактов упал'
timeout 900 node harvest/run.js links || echo '  ! база авто со ссылками не пересобралась'
node harvest/run.js stats

# Спрос: Wordstat + Вебмастер + GSC → семантика → сео-память. Без ключей команда
# честно скажет об этом в лог и не свалит остальное.
timeout 1800 node seo/cli.js demand || echo '  ! цикл спроса не доехал'
echo "=== $(TZ=Europe/Moscow date '+%F %H:%M МСК') готово"
