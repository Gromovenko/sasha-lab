#!/bin/bash
# Хвост захода: дождаться, пока освободится замок идущей очереди, добрать
# оставшиеся источники и сразу разобрать накопленное в факты.
#
#   scripts/harvest-stage2.sh host1 host2 ...
#
# Зачем отдельный скрипт, а не «запустить второй очередью»: сбор на сервере
# идёт в ОДНОМ экземпляре (общий flock, см. harvest-queue.sh), поэтому второй
# заход, запущенный поверх идущего, просто вышел бы с кодом 99 и хвост остался
# бы несобранным до следующего воскресенья. Здесь мы ждём освобождения замка
# столько, сколько нужно, и только потом отдаём хосты обычной очереди.
#
# Разбор фактов идёт ПОСЛЕ сбора, а не параллельно: он упирается в CPU (около
# 12 документов в секунду), а на сервере два ядра — вместе со сбором оба шага
# просто растянулись бы вдвое.
set -u
cd /opt/sasha-lab 2>/dev/null || cd "$(dirname "$0")/.." || exit 1

LOCK="${HARVEST_LOCK:-/tmp/sashalab-harvest.lock}"
WAIT_S="${HARVEST_WAIT_S:-86400}"          # сколько ждём чужую очередь
msg() { echo "$(TZ=Europe/Moscow date '+%F %H:%M МСК') $*"; }

[ $# -gt 0 ] || { echo "укажите хосты: $0 host1 [host2 ...]"; exit 2; }

msg "хвост захода: жду освобождения замка $LOCK (до $WAIT_S с)"
# Замок только ждём, но НЕ держим: держать его здесь нельзя — очередь берёт
# тот же самый замок и упёрлась бы сама в себя.
flock -w "$WAIT_S" "$LOCK" true || { msg "замок не освободился за $WAIT_S с — хвост не запущен"; exit 3; }
msg "замок свободен, запускаю сбор: $*"

# Гонка возможна ровно в одном случае: между освобождением замка и нашим
# стартом успел сесть воскресный крон. Тогда очередь выйдет с 99 — ждём и
# пробуем ещё раз, а не теряем хвост.
for try in 1 2 3; do
  HARVEST_PAR="${HARVEST_PAR:-2}" scripts/harvest-queue.sh "$@"; rc=$?
  [ "$rc" != 99 ] && break
  msg "замок снова занят (попытка $try) — жду 10 минут"; sleep 600
done
msg "сбор завершён код=$rc"

msg "разбор накопленного в факты"
scripts/facts-backlog.sh
msg "хвост захода пройден"
