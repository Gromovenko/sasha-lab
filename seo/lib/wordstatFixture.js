// Форма ответа повторяет yandex.wordstatTop: { totalCount, results, associations }.
// Ассоциации («что ещё искали») отдаём соседними сидами — так же, как Яндекс.
function top(phrase) {
  const rows = FIXTURE[phrase];
  if (!rows) {
    // Неизвестный сид: отдаём пустой ответ, а не выдуманные строки — иначе
    // тестовый режим начнёт «подтверждать» любую фантазию.
    return { totalCount: 0, results: [], associations: [] };
  }
  return {
    totalCount: rows.reduce((a, [, c]) => a + c, 0),
    results: rows.map(([p, count]) => ({ phrase: p, count })),
    associations: [],
  };
}

const seeds = () => Object.keys(FIXTURE);

module.exports = { top, seeds, FIXTURE };
